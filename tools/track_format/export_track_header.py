#!/usr/bin/env python3
"""Convert a validated boonta-track-v1 JSON track into a C header."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from validate_track import TrackValidationError, load_track


def identifier(name: str) -> str:
    result = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not result or result[0].isdigit():
        result = "track_" + result
    return result.upper()


def render_header(track: dict, symbol: str | None = None) -> str:
    points = track["points"]
    symbol = identifier(symbol or track["name"])
    rows = []
    for point in points:
        checkpoint = "1" if point["checkpoint"] else "0"
        rows.append(
            "    { %.6ff, %.6ff, %.6ff, %.6ff, %s }"
            % (point["x"], point["y"], point["z"], point["half_width"], checkpoint)
        )
    point_type = """typedef struct {
    float x;
    float y;
    float z;
    float half_width;
    unsigned char checkpoint;
} BoontaTrackPoint;"""
    return (
        "/* Generated by tools/track_format/export_track_header.py. Do not edit. */\n"
        "#ifndef BOONTA_GENERATED_TRACK_%s_H\n#define BOONTA_GENERATED_TRACK_%s_H\n\n"
        "#define BOONTA_TRACK_CLOSED_LOOP %s\n"
        "#define BOONTA_TRACK_POINT_COUNT %dU\n\n"
        "%s\n\n"
        "static const BoontaTrackPoint boonta_track_points_%s[BOONTA_TRACK_POINT_COUNT] = {\n"
        "%s\n};\n\n#endif /* BOONTA_GENERATED_TRACK_%s_H */\n"
    ) % (
        symbol, symbol, "1" if track["closed_loop"] else "0",
        len(points), point_type, symbol.lower(), ",\n".join(rows), symbol,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("track", help="input boonta-track-v1 JSON file")
    parser.add_argument("output", help="output C header path")
    parser.add_argument("--symbol", help="optional C symbol name")
    args = parser.parse_args()
    try:
        track = load_track(args.track)
        header = render_header(track, args.symbol)
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(header, encoding="utf-8")
    except (TrackValidationError, OSError) as exc:
        print(f"track export failed: {exc}", file=sys.stderr)
        return 1
    print(f"exported {len(track['points'])} points to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
