#!/usr/bin/env python3
"""Convert a validated boonta-mesh-v1 source file into a C header."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from validate_mesh import MeshValidationError, load_mesh, validate_mesh


def identifier(name: str) -> str:
    """Normalize an authored mesh name into a valid, stable C identifier."""
    result = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not result or result[0].isdigit():
        result = "mesh_" + result
    return result.lower()


def render_header(data: dict) -> str:
    """Return deterministic C source for one validated mesh."""
    mesh = validate_mesh(data)
    suffix = identifier(mesh["name"])
    guard = f"BOONTA_GENERATED_MESH_{suffix.upper()}_H"
    vertices_name = f"boonta_generated_mesh_{suffix}_vertices"
    indices_name = f"boonta_generated_mesh_{suffix}_indices"
    view_name = f"boonta_generated_mesh_{suffix}_view"

    vertex_rows = []
    for vertex in mesh["vertices"]:
        x, y, z = vertex["position"]
        r, g, b, a = vertex["color"]
        u, v = vertex["uv"]
        vertex_rows.append(
            "    { %.6ff, %.6ff, %.6ff, %dU, %dU, %dU, %dU, %.6ff, %.6ff }"
            % (x, y, z, r, g, b, a, u, v)
        )

    index_rows = []
    for start in range(0, len(mesh["indices"]), 12):
        row = mesh["indices"][start : start + 12]
        index_rows.append("    " + ", ".join(f"{index}U" for index in row))

    return (
        "/* Generated by tools/mesh_format/export_mesh_header.py. Do not edit. */\n"
        f"#ifndef {guard}\n#define {guard}\n\n"
        '#include "mesh_data.h"\n\n'
        f"static const BoontaMeshVertex {vertices_name}[{len(mesh['vertices'])}U] = {{\n"
        + ",\n".join(vertex_rows)
        + "\n};\n\n"
        + f"static const uint16_t {indices_name}[{len(mesh['indices'])}U] = {{\n"
        + ",\n".join(index_rows)
        + "\n};\n\n"
        + f"static const BoontaMeshView {view_name} = {{\n"
        + f"    {vertices_name},\n"
        + f"    {len(mesh['vertices'])}U,\n"
        + f"    sizeof({vertices_name}),\n"
        + f"    {indices_name},\n"
        + f"    {len(mesh['indices'])}U,\n"
        + f"    sizeof({indices_name})\n"
        + "};\n\n"
        + f"#endif /* {guard} */\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", help="input boonta-mesh-v1 JSON file")
    parser.add_argument("output", help="output generated C header path")
    args = parser.parse_args()
    try:
        mesh = load_mesh(args.input)
        header = render_header(mesh)
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(header, encoding="utf-8")
    except (MeshValidationError, OSError) as exc:
        print(f"mesh export failed: {exc}", file=sys.stderr)
        return 1
    print(
        f"exported {len(mesh['vertices'])} vertices and {len(mesh['indices'])} indices "
        f"to {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
