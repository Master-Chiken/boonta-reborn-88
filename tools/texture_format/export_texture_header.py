#!/usr/bin/env python3
"""Convert a validated boonta-rgb565-v1 JSON texture into a GX-tiled C header."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from validate_texture import TextureValidationError, load_texture, validate_texture


def identifier(name: str) -> str:
    """Normalize an authored texture name into a stable C identifier."""
    result = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not result or result[0].isdigit():
        result = "texture_" + result
    return result.lower()


def pack_rgb565(rgb: list[int]) -> int:
    """Quantize one RGB8 pixel to the unsigned RGB565 value used by GX."""
    r, g, b = rgb
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def gx_tiled_pixels(data: dict) -> list[int]:
    """Return source pixels reordered in GX 4x4 tile order."""
    texture = validate_texture(data)
    width, height, source = texture["width"], texture["height"], texture["pixels"]
    result = []
    for tile_y in range(0, height, 4):
        for tile_x in range(0, width, 4):
            for y in range(tile_y, tile_y + 4):
                for x in range(tile_x, tile_x + 4):
                    result.append(pack_rgb565(source[y * width + x]))
    return result


def render_header(data: dict) -> str:
    """Return deterministic C source with GX-tiled RGB565 texels."""
    texture = validate_texture(data)
    suffix = identifier(texture["name"])
    upper = suffix.upper()
    guard = f"BOONTA_GENERATED_TEXTURE_{upper}_H"
    pixels_name = f"boonta_generated_texture_{suffix}_pixels"
    packed = gx_tiled_pixels(texture)
    rows = []
    for start in range(0, len(packed), 8):
        rows.append("    " + ", ".join(f"0x{value:04X}U" for value in packed[start:start + 8]))
    return (
        "/* Generated by tools/texture_format/export_texture_header.py. Do not edit. */\n"
        f"#ifndef {guard}\n#define {guard}\n\n"
        "#include <stdint.h>\n\n"
        f"#define BOONTA_GENERATED_TEXTURE_{upper}_WIDTH {texture['width']}U\n"
        f"#define BOONTA_GENERATED_TEXTURE_{upper}_HEIGHT {texture['height']}U\n\n"
        f"static const uint16_t {pixels_name}[{len(packed)}U] = {{\n"
        + ",\n".join(rows)
        + "\n};\n\n"
        + f"#endif /* {guard} */\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", help="input boonta-rgb565-v1 JSON file")
    parser.add_argument("output", help="output generated C header path")
    args = parser.parse_args()
    try:
        texture = load_texture(args.input)
        header = render_header(texture)
        output = Path(args.output)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(header, encoding="utf-8")
    except (TextureValidationError, OSError) as exc:
        print(f"texture export failed: {exc}", file=sys.stderr)
        return 1
    print(
        f"exported {texture['width']}x{texture['height']} RGB565 texture "
        f"({len(texture['pixels'])} source pixels) to {args.output}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
